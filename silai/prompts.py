def calendar_table(days: int = 21, today: dt.date | None = None) -> str:
    """Next-N-days lookup table so the model never does weekday arithmetic.
    Volatile (depends on today) - keep OUT of any cached prefix."""
    today = today or dt.datetime.now(IST).date()
    lines = []
    for i in range(days):
        d = today + dt.timedelta(days=i)
        tag = " (आज)" if i == 0 else (" (कल)" if i == 1 else (" (परसों)" if i == 2 else ""))
        lines.append(f"{HINDI_DAYS_SHORT[d.weekday()]} {d.day} {HINDI_MONTHS[d.month - 1]} = {d.isoformat()}{tag}")
    return "आने वाले दिनों का calendar (तारीख़ें यहीं से लो, खुद हिसाब मत लगाओ):\n" + "\n".join(lines)


def notes_context(notes: list[dict]) -> str:
    """Suhani's remembered personal context, injected each session. Empty string if none."""
    if not notes:
        return ""
    lines = "\n".join(f"[{n['id']}] {n['content']} ({n['created_at'][:10]})" for n in notes)
    return "सुहानी की यादें (पिछली बातचीतों से):\n" + lines


def date_context(now: dt.datetime | None = None) -> str:
    """Volatile suffix - keep OUT of the cached prefix."""
    now = now or dt.datetime.now(IST)
    weekday = HINDI_WEEKDAYS[now.weekday()]
    return f"आज {weekday} है, तारीख़ {now.date().isoformat()} (समय {now.strftime('%H:%M')} IST)।"


